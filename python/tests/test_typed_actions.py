"""The typed builders added for the operator and governance actions encode to
the shared conformance vectors byte for byte.

`conformance/codec.ndjson` is generated by the Rust core and replayed by the
TypeScript suite (`src/conformance.test.ts`), so a builder that reproduces a
vector's payload produces the same bytes as the TypeScript encoder.
"""

from __future__ import annotations

import inspect
import json
import re
from pathlib import Path

import pytest
from proof_trading_sdk import actions

_CODEC = Path(__file__).resolve().parents[2] / "conformance" / "codec.ndjson"


def _vector(case: str) -> dict:
    for line in _CODEC.read_text().splitlines():
        if line.strip():
            c = json.loads(line)
            if c["case"] == case:
                return c
    raise KeyError(case)


def _b(v):
    """Vector byte fields are u8 arrays; the builders take ``bytes``."""
    return bytes(v)


def _proof(p: dict) -> actions.OperatorReceiptProof:
    return actions.OperatorReceiptProof(
        signatures=[_b(s) for s in p["signatures"]],
        signer_bitmap=_b(p["signer_bitmap"]),
    )


_BYTE_RECEIPT_FIELDS = {
    "proof_owner",
    "destination_owner",
    "destination_token_acct",
    "solana_tx_signature",
    "finalized_blockhash",
    "deployment_id",
    "authorization_digest",
}


def _receipt(r: dict) -> actions.BridgeWithdrawalReceipt:
    return actions.BridgeWithdrawalReceipt(
        **{k: _b(v) if k in _BYTE_RECEIPT_FIELDS else v for k, v in r.items()}
    )


def _admin(i: dict, *byte_keys: str) -> dict:
    return {k: _b(v) if k in byte_keys else v for k, v in i.items()}


def _limb(limb: dict | None) -> actions.TriggerLimb | None:
    return None if limb is None else actions.TriggerLimb(**limb)


def _entry(order: dict) -> actions.OrderEntry:
    shared = {
        "client_order_id": order["client_order_id"],
        "reduce_only": order["reduce_only"],
        "stop_loss": _limb(order["stop_loss"]),
        "take_profit": _limb(order["take_profit"]),
    }
    kind = order["kind"]
    if "Market" in kind:
        return actions.OrderEntry.market_order(
            order["market"],
            order["side"],
            order["quantity"],
            worst_price=kind["Market"]["worst_price"],
            **shared,
        )
    limit = kind["Limit"]
    return actions.OrderEntry(
        market=order["market"],
        side=order["side"],
        price=limit["price"],
        quantity=order["quantity"],
        post_only=limit["post_only"],
        time_in_force=limit["time_in_force"],
        **shared,
    )


def _place_orders(i: dict) -> actions.PlaceOrders:
    return actions.PlaceOrders(
        owner=_b(i["owner"]), orders=[_entry(order) for order in i["orders"]]
    )


def _cancel_orders(i: dict) -> actions.CancelOrders:
    return actions.CancelOrders(owner=_b(i["owner"]), order_ids=i["order_ids"])


def _cancel_client_orders(i: dict) -> actions.CancelClientOrders:
    return actions.CancelClientOrders(
        owner=_b(i["owner"]), client_order_ids=i["client_order_ids"]
    )


BUILDERS = {
    "create_market/full": lambda i: actions.CreateMarket(**_admin(i, "signer")),
    "authorize_withdrawal/operator": lambda i: actions.AuthorizeWithdrawal(
        authorization=_b(i["authorization"]), proof=_proof(i["proof"])
    ),
    "confirm_withdrawal_receipt/paid": lambda i: actions.ConfirmWithdrawalReceipt(
        receipt=_receipt(i["receipt"]), proof=_proof(i["proof"])
    ),
    "fail_withdrawal_receipt/cancelled": lambda i: actions.FailWithdrawalReceipt(
        receipt=_receipt(i["receipt"]), proof=_proof(i["proof"])
    ),
    "propose_admin_action/create_market": lambda i: actions.ProposeAdminAction(
        **_admin(i, "proposer")
    ),
    "approve_admin_action/rotate_registry": lambda i: actions.ApproveAdminAction(
        **_admin(i, "approver", "proposer", "content_hash")
    ),
    "reject_admin_action/basic": lambda i: actions.RejectAdminAction(
        **_admin(i, "rejecter", "content_hash")
    ),
    "emergency_admin_action/pause_market": lambda i: actions.EmergencyAdminAction(
        **_admin(i, "signer")
    ),
    "record_withdrawal_payout/basic": lambda i: actions.RecordWithdrawalPayout(
        **_admin(i, "holder", "solana_signature")
    ),
    "propose_admin_action/set_deposit_limit": lambda i: actions.ProposeAdminAction(
        **_admin(i, "proposer")
    ),
    "propose_admin_action/set_market_status": lambda i: actions.ProposeAdminAction(
        **_admin(i, "proposer")
    ),
    **{
        f"place_orders/{name}": _place_orders
        for name in (
            "limit_min",
            "limit_flags_cloid_ioc",
            "limit_max_u64",
            "limit_with_triggers",
            "market_basic",
            "market_worst_price_with_triggers",
            "close",
            "engine_list",
        )
    },
    "cancel_orders/one": _cancel_orders,
    "cancel_orders/two_orders": _cancel_orders,
    "cancel_client_orders/one": _cancel_client_orders,
    "cancel_client_orders/two_orders": _cancel_client_orders,
}


def _single_from_list(c: dict) -> actions.Action:
    """The single-order action whose list of one is vector *c*."""
    i = c["input"]
    owner = _b(i["owner"])
    if "order_ids" in i:
        (order_id,) = i["order_ids"]
        return actions.CancelOrder(order_id=order_id, owner=owner)
    if "client_order_ids" in i:
        (client_order_id,) = i["client_order_ids"]
        return actions.CancelClientOrder(owner=owner, client_order_id=client_order_id)
    (entry,) = [_entry(order) for order in i["orders"]]
    shared = {
        "market": entry.market,
        "owner": owner,
        "side": entry.side,
        "quantity": entry.quantity,
        "client_order_id": entry.client_order_id,
        "stop_loss": entry.stop_loss,
        "take_profit": entry.take_profit,
    }
    if entry.kind == actions.ORDER_KIND_MARKET:
        return actions.MarketOrder(
            **shared, worst_price=entry.worst_price, reduce_only=entry.reduce_only
        )
    return actions.PlaceOrder(
        **shared,
        price=entry.price,
        post_only=entry.post_only,
        reduce_only=entry.reduce_only,
        time_in_force=entry.time_in_force,
    )


@pytest.mark.parametrize(
    "case",
    [
        "place_orders/limit_min",
        "place_orders/limit_flags_cloid_ioc",
        "place_orders/limit_max_u64",
        "place_orders/limit_with_triggers",
        "place_orders/market_basic",
        "place_orders/market_worst_price_with_triggers",
        "place_orders/close",
        "cancel_orders/one",
        "cancel_client_orders/one",
    ],
)
def test_single_actions_send_the_list_of_one(case):
    c = _vector(case)
    action_type, payload = actions.encode_action(_single_from_list(c))
    assert action_type == c["action_type"]
    assert payload.hex() == c["expect"]["payload_hex"]


@pytest.mark.parametrize("case", sorted(BUILDERS))
def test_typed_builder_matches_the_shared_vector(case):
    c = _vector(case)
    action = BUILDERS[case](c["input"])
    action_type, payload = actions.encode_action(action)
    assert action_type == c["action_type"]
    assert payload.hex() == c["expect"]["payload_hex"]


def test_the_unit_admin_arm_is_a_bare_string():
    propose = actions.ProposeAdminAction(
        proposer=bytes(20), registry_version=1, action="UnpauseBridge"
    )
    _, payload = actions.encode_action(propose)
    assert actions.decode_action(propose.action_type, payload)["action"] == (
        "UnpauseBridge"
    )


def _typescript_action_names() -> set[str]:
    """Keys of the hand-written TypeScript ``ActionType`` map, which the Rust
    test ``action_type_map`` holds to the core in both directions."""
    src = (_CODEC.parents[1] / "src" / "types.ts").read_text()
    body = src.split("export const ActionType = {", 1)[1].split("} as const;", 1)[0]
    names = set(re.findall(r"^\s*([A-Za-z0-9]+):\s*0x[0-9a-fA-F]+,", body, re.M))
    assert len(names) >= 30, f"the extractor read only {len(names)} names"
    return names


def test_every_published_action_has_a_typed_builder():
    built = {
        cls.ACTION_NAME
        for _, cls in inspect.getmembers(actions, inspect.isclass)
        if issubclass(cls, actions.Action) and cls.ACTION_NAME
    }
    missing = _typescript_action_names() - built
    assert missing == set(), "actions reachable only through RawAction"


_ENTRY = actions.OrderEntry(market=1, side="Buy", price=1, quantity=1)
_LISTS = {
    "place": lambda n: actions.PlaceOrders(owner=bytes(20), orders=[_ENTRY] * n),
    "cancel": lambda n: actions.CancelOrders(owner=bytes(20), order_ids=[1] * n),
    "cancel_client": lambda n: actions.CancelClientOrders(
        owner=bytes(20), client_order_ids=[1] * n
    ),
}


@pytest.mark.parametrize("kind", sorted(_LISTS))
@pytest.mark.parametrize("count", [0, 101])
def test_a_list_out_of_range_does_not_encode(kind, count):
    with pytest.raises(ValueError, match=rf"list carries {count} entries"):
        actions.encode_action(_LISTS[kind](count))


@pytest.mark.parametrize("kind", sorted(_LISTS))
def test_a_full_list_encodes(kind):
    action_type, _ = actions.encode_action(_LISTS[kind](actions.MAX_LIST_ENTRIES))
    assert action_type == _LISTS[kind](1).action_type


def test_single_names_share_the_list_bytes():
    assert actions.ActionType.PlaceOrder == actions.ActionType.PlaceOrders == 0x35
    assert actions.ActionType.MarketOrder == actions.ActionType.PlaceOrders
    assert actions.ActionType.CancelOrder == actions.ActionType.CancelOrders == 0x36
    assert (
        actions.ActionType.CancelClientOrder
        == actions.ActionType.CancelClientOrders
        == 0x37
    )


def test_an_entry_is_a_limit_or_a_market_order():
    with pytest.raises(ValueError, match="needs a price"):
        actions.OrderEntry(market=1, side="Buy", price=None, quantity=1)
    with pytest.raises(ValueError, match="worst_price is for market entries"):
        actions.OrderEntry(market=1, side="Buy", price=1, quantity=1, worst_price=2)
    with pytest.raises(ValueError, match="has no price"):
        actions.OrderEntry(market=1, side="Buy", price=1, quantity=1, kind="market")
    with pytest.raises(ValueError, match="unknown order kind"):
        actions.OrderEntry(market=1, side="Buy", price=1, quantity=1, kind="stop")


def test_a_list_of_one_encodes_as_the_single_order():
    single = actions.PlaceOrder(
        market=1, owner=bytes(20), side="Buy", price=100, quantity=10
    )
    listed = actions.PlaceOrders(
        owner=bytes(20),
        orders=[actions.OrderEntry(market=1, side="Buy", price=100, quantity=10)],
    )
    assert actions.encode_action(listed) == actions.encode_action(single)
