"""The typed builders added for the operator and governance actions encode to
the shared conformance vectors byte for byte.

`conformance/codec.ndjson` is generated by the Rust core and replayed by the
TypeScript suite (`src/conformance.test.ts`), so a builder that reproduces a
vector's payload produces the same bytes as the TypeScript encoder.
"""

from __future__ import annotations

import inspect
import json
import re
from pathlib import Path

import pytest
from proof_trading_sdk import actions

_CODEC = Path(__file__).resolve().parents[2] / "conformance" / "codec.ndjson"


def _vector(case: str) -> dict:
    for line in _CODEC.read_text().splitlines():
        if line.strip():
            c = json.loads(line)
            if c["case"] == case:
                return c
    raise KeyError(case)


def _b(v):
    """Vector byte fields are u8 arrays; the builders take ``bytes``."""
    return bytes(v)


def _proof(p: dict) -> actions.OperatorReceiptProof:
    return actions.OperatorReceiptProof(
        signatures=[_b(s) for s in p["signatures"]],
        signer_bitmap=_b(p["signer_bitmap"]),
    )


_BYTE_RECEIPT_FIELDS = {
    "proof_owner",
    "destination_owner",
    "destination_token_acct",
    "solana_tx_signature",
    "finalized_blockhash",
    "deployment_id",
    "authorization_digest",
}


def _receipt(r: dict) -> actions.BridgeWithdrawalReceipt:
    return actions.BridgeWithdrawalReceipt(
        **{k: _b(v) if k in _BYTE_RECEIPT_FIELDS else v for k, v in r.items()}
    )


def _admin(i: dict, *byte_keys: str) -> dict:
    return {k: _b(v) if k in byte_keys else v for k, v in i.items()}


BUILDERS = {
    "oracle_update/no_publish_time": lambda i: actions.OracleUpdate(
        **_admin(i, "signer")
    ),
    "create_market/full": lambda i: actions.CreateMarket(**_admin(i, "signer")),
    "authorize_withdrawal/operator": lambda i: actions.AuthorizeWithdrawal(
        authorization=_b(i["authorization"]), proof=_proof(i["proof"])
    ),
    "confirm_withdrawal_receipt/paid": lambda i: actions.ConfirmWithdrawalReceipt(
        receipt=_receipt(i["receipt"]), proof=_proof(i["proof"])
    ),
    "fail_withdrawal_receipt/cancelled": lambda i: actions.FailWithdrawalReceipt(
        receipt=_receipt(i["receipt"]), proof=_proof(i["proof"])
    ),
    "propose_admin_action/create_market": lambda i: actions.ProposeAdminAction(
        **_admin(i, "proposer")
    ),
    "approve_admin_action/rotate_registry": lambda i: actions.ApproveAdminAction(
        **_admin(i, "approver", "proposer", "content_hash")
    ),
    "reject_admin_action/basic": lambda i: actions.RejectAdminAction(
        **_admin(i, "rejecter", "content_hash")
    ),
    "emergency_admin_action/pause_market": lambda i: actions.EmergencyAdminAction(
        **_admin(i, "signer")
    ),
}


@pytest.mark.parametrize("case", sorted(BUILDERS))
def test_typed_builder_matches_the_shared_vector(case):
    c = _vector(case)
    action = BUILDERS[case](c["input"])
    action_type, payload = actions.encode_action(action)
    assert action_type == c["action_type"]
    assert payload.hex() == c["expect"]["payload_hex"]


def test_the_unit_admin_arm_is_a_bare_string():
    propose = actions.ProposeAdminAction(
        proposer=bytes(20), registry_version=1, action="UnpauseBridge"
    )
    _, payload = actions.encode_action(propose)
    assert actions.decode_action(propose.action_type, payload)["action"] == (
        "UnpauseBridge"
    )


def _typescript_action_names() -> set[str]:
    """Keys of the hand-written TypeScript ``ActionType`` map, which the Rust
    test ``action_type_map`` holds to the core in both directions."""
    src = (_CODEC.parents[1] / "src" / "types.ts").read_text()
    body = src.split("export const ActionType = {", 1)[1].split("} as const;", 1)[0]
    names = set(re.findall(r"^\s*([A-Za-z0-9]+):\s*0x[0-9a-fA-F]+,", body, re.M))
    assert len(names) >= 30, f"the extractor read only {len(names)} names"
    return names


def test_every_published_action_has_a_typed_builder():
    built = {
        cls.ACTION_NAME
        for _, cls in inspect.getmembers(actions, inspect.isclass)
        if issubclass(cls, actions.Action) and cls.ACTION_NAME
    }
    missing = _typescript_action_names() - built
    assert missing == set(), "actions reachable only through RawAction"
