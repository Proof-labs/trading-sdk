import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { decodeTx, encodePayloadBytes, encodeSignedTx } from "./codec.js";
import { bytesToHex } from "./crypto.js";
import {
  ACTION_TAG_BY_KIND,
  decodeAdminAction,
  decodeProposalDisplayInfo,
} from "./governance-query.js";
import type { Action, AdminAction, SetDepositLimit } from "./types.js";

const config: SetDepositLimit = {
  perDepositMaxMicroUsdc: 10_000_000_000n,
  windowCapMicroUsdc: 30_000_000_000n,
  windowSecs: 86_400,
};
const admin = (value = config): AdminAction => ({
  kind: "SetDepositLimit",
  value,
});
const propose = (value = config): Action => ({
  type: "ProposeAdminAction",
  data: {
    proposer: new Uint8Array(20).fill(0xa1),
    registryVersion: 1n,
    action: admin(value),
  },
});

// Generated by: cargo run -p proof-trading-sdk-conformance --bin gen-vectors
const vector = readFileSync(
  new URL("../conformance/codec.ndjson", import.meta.url),
  "utf8",
)
  .trim()
  .split("\n")
  .map((line) => JSON.parse(line))
  .find((entry) => entry.case === "propose_admin_action/set_deposit_limit");

describe("SetDepositLimit", () => {
  it("matches the public Rust wire vector", () => {
    expect(vector).toBeDefined();
    expect(bytesToHex(encodePayloadBytes(propose()))).toBe(
      vector.expect.payload_hex,
    );
  });

  it.each([
    config,
    { perDepositMaxMicroUsdc: 0n, windowCapMicroUsdc: 0n, windowSecs: 1 },
    {
      perDepositMaxMicroUsdc: (1n << 64n) - 1n,
      windowCapMicroUsdc: 9_007_199_254_740_993n,
      windowSecs: 0xffff_ffff,
    },
  ])(
    "round-trips independent caps without losing integer precision (case %#)",
    (value) => {
      const action = propose(value);
      const tx = encodeSignedTx(
        action,
        12n,
        new Uint8Array(32),
        new Uint8Array(64),
      );
      expect(decodeTx(tx).action).toEqual(action);
    },
  );

  it("reads a tag-28 proposal and rejects a mismatched tag", () => {
    const tuple = {
      SetDepositLimit: [
        config.perDepositMaxMicroUsdc,
        config.windowCapMicroUsdc,
        config.windowSecs,
      ],
    };
    expect(decodeAdminAction(tuple)).toEqual(admin());
    expect(ACTION_TAG_BY_KIND.SetDepositLimit).toBe(28);
    const raw = [
      1,
      "Pending",
      "Pending",
      1,
      2,
      Array(20).fill(0xa1),
      [],
      [],
      7,
      1000,
      2000,
      28,
      tuple,
      [],
      Array(32).fill(0),
    ];
    expect(decodeProposalDisplayInfo(raw).action).toEqual(admin());
    raw[11] = 19;
    expect(() => decodeProposalDisplayInfo(raw)).toThrow(
      "does not match SetDepositLimit tag 28",
    );
  });

  it("rejects malformed wire tuples", () => {
    expect(() => decodeAdminAction({ SetDepositLimit: [1, 2] })).toThrow();
  });

  it.each([
    { ...config, perDepositMaxMicroUsdc: -1n },
    { ...config, windowCapMicroUsdc: 1n << 64n },
    { ...config, windowSecs: 0x1_0000_0000 },
  ])("rejects values outside the wire integer ranges", (value) => {
    expect(() => encodePayloadBytes(propose(value))).toThrow();
  });
});
