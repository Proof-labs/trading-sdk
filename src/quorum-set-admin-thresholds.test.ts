// The admin quorum's SetAdminThresholds (inner tag 37): how many approvals
// each severity of admin action needs.

import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  decodeTx,
  encodePayloadBytes,
  encodeSignedTx,
  signAndEncode,
} from "./codec.js";
import { bytesToHex, hexToBytes, UNBOUND_CHAIN_ID } from "./crypto.js";
import { ACTION_TAG_BY_KIND, decodeAdminAction } from "./governance-query.js";
import type { Action, AdminAction, AdminThresholds } from "./types.js";

/** proof-wire's frozen `vectors/propose_set_admin_thresholds.hex`, copied
 *  byte for byte: the default table (stop 1, low impact 2, high impact 3),
 *  proposed by `0xA1` × 20 under registry version 1. Key `0x42` × 32 signs
 *  it on the unbound chain at seq 501. */
const FROZEN = readFileSync(
  new URL(
    "../crates/spec/golden-vectors/propose_set_admin_thresholds.hex",
    import.meta.url,
  ),
  "utf8",
).trim();

const DEFAULT_TABLE: AdminThresholds = { stop: 1, lowImpact: 2, highImpact: 3 };

const admin = (table: AdminThresholds): AdminAction => ({
  kind: "SetAdminThresholds",
  value: table,
});

const propose = (action: AdminAction): Action => ({
  type: "ProposeAdminAction",
  data: {
    proposer: new Uint8Array(20).fill(0xa1),
    registryVersion: 1n,
    action,
  },
});

// Generated by: cargo run -p proof-trading-sdk-conformance --bin gen-vectors
const vector = readFileSync(
  new URL("../conformance/codec.ndjson", import.meta.url),
  "utf8",
)
  .trim()
  .split("\n")
  .map((line) => JSON.parse(line))
  .find((entry) => entry.case === "propose_admin_action/set_admin_thresholds");

describe("quorum SetAdminThresholds", () => {
  it("builds the engine's frozen proposal byte for byte", () => {
    const wire = signAndEncode(
      UNBOUND_CHAIN_ID,
      propose(admin(DEFAULT_TABLE)),
      501n,
      new Uint8Array(32).fill(0x42),
    );
    expect(bytesToHex(wire)).toBe(FROZEN);
  });

  it("decodes the frozen proposal back to its inputs", () => {
    const { action, seq } = decodeTx(hexToBytes(FROZEN));
    expect(seq).toBe(501n);
    expect(action).toEqual(propose(admin(DEFAULT_TABLE)));
  });

  it("keeps each severity in its own slot", () => {
    expect(vector).toBeDefined();
    const action = propose(admin({ stop: 1, lowImpact: 3, highImpact: 4 }));
    expect(bytesToHex(encodePayloadBytes(action))).toBe(
      vector.expect.payload_hex,
    );
    const tx = encodeSignedTx(
      action,
      12n,
      new Uint8Array(32),
      new Uint8Array(64),
    );
    expect(decodeTx(tx).action).toEqual(action);
  });

  it("reads a stored tag-37 action under its own kind", () => {
    expect(decodeAdminAction({ SetAdminThresholds: [1, 2, 3] })).toEqual(
      admin(DEFAULT_TABLE),
    );
    expect(ACTION_TAG_BY_KIND.SetAdminThresholds).toBe(37);
  });

  it("refuses a table the engine refuses without reading state", () => {
    expect(() =>
      encodePayloadBytes(
        propose(admin({ stop: 1, lowImpact: 1, highImpact: 3 })),
      ),
    ).toThrow(/lowImpact 1 is below 2/);
    expect(() =>
      encodePayloadBytes(
        propose(admin({ stop: 3, lowImpact: 2, highImpact: 3 })),
      ),
    ).toThrow(/must rise with severity/);
    expect(() =>
      encodePayloadBytes(
        propose(admin({ stop: 0, lowImpact: 2, highImpact: 3 })),
      ),
    ).toThrow(/stop 0 is not a count of at least 1/);
    expect(() =>
      encodePayloadBytes(
        propose(admin({ stop: 2, lowImpact: 2, highImpact: 2 })),
      ),
    ).not.toThrow();
  });
});
