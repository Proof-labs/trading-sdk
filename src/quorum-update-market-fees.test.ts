// The admin quorum's UpdateMarketFees (inner tag 35): a live market's settings
// change, proposed against the market's settings sequence.

import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  decodeTx,
  encodePayloadBytes,
  encodeSignedTx,
  signAndEncode,
} from "./codec.js";
import { bytesToHex, hexToBytes, UNBOUND_CHAIN_ID } from "./crypto.js";
import {
  ACTION_TAG_BY_KIND,
  decodeAdminAction,
  decodeProposalDisplayInfo,
} from "./governance-query.js";
import type { Action, AdminAction, MarketSettingsChange } from "./types.js";

/** proof-wire's frozen `vectors/propose_update_market_fees.hex`, copied byte
 *  for byte: DevNet BTC (market 1) raises its open-interest cap to 35,000 at
 *  settings sequence 0, every other setting left as it is, proposed by
 *  `0xA1` × 20 under registry version 1. Key `0x42` × 32 signs it on the
 *  unbound chain at seq 400. */
const FROZEN = readFileSync(
  new URL(
    "../crates/spec/golden-vectors/propose_update_market_fees.hex",
    import.meta.url,
  ),
  "utf8",
).trim();

/** The frozen proposal's change as a caller writes it. */
const RAISE_CAP: MarketSettingsChange = { market: 1, maxOpenInterest: 35_000n };

/** The same change as it decodes: every field it leaves empty is `null`. */
const RAISE_CAP_DECODED: MarketSettingsChange = {
  market: 1,
  takerFeeBps: null,
  makerFeeBps: null,
  maxFundingRateBps: null,
  fundingIntervalMs: null,
  maxPositionSize: null,
  defaultTtlMs: null,
  netDeltaMargin: null,
  tickSize: null,
  lotSize: null,
  primaryOracleSigner: null,
  oracleStalenessMs: null,
  markSourceMode: null,
  maxMarkSpreadBps: null,
  cexCompositeStalenessMs: null,
  feeTiers: null,
  imBps: null,
  mmBps: null,
  maxOpenInterest: 35_000n,
  impactNotional: null,
  fundingDeadBandBps: null,
  fundingInterestRate: null,
};

/** Every field set to its own value, as in the shared conformance vector
 *  `propose_admin_action/update_market_fees`. */
const EVERY_FIELD: MarketSettingsChange = {
  market: 7,
  takerFeeBps: 1,
  makerFeeBps: 2,
  maxFundingRateBps: 3,
  fundingIntervalMs: 4n,
  maxPositionSize: 5n,
  defaultTtlMs: 6n,
  netDeltaMargin: true,
  tickSize: 8n,
  lotSize: 9n,
  primaryOracleSigner: new Uint8Array(20).fill(0x0a),
  oracleStalenessMs: 11n,
  markSourceMode: 1,
  maxMarkSpreadBps: 13,
  cexCompositeStalenessMs: 14n,
  feeTiers: [
    { min30dVolumeMicroUsdc: 0n, makerFeeTenthBps: -15, takerFeeTenthBps: 15 },
  ],
  imBps: 16,
  mmBps: 17,
  maxOpenInterest: 18n,
  impactNotional: 19n,
  fundingDeadBandBps: 20,
  fundingInterestRate: -21,
};

const admin = (
  change: MarketSettingsChange,
  predecessor = 0n,
): AdminAction => ({
  kind: "UpdateMarketFees",
  value: { predecessor, change },
});

const propose = (action: AdminAction): Action => ({
  type: "ProposeAdminAction",
  data: {
    proposer: new Uint8Array(20).fill(0xa1),
    registryVersion: 1n,
    action,
  },
});

// Generated by: cargo run -p proof-trading-sdk-conformance --bin gen-vectors
const vector = readFileSync(
  new URL("../conformance/codec.ndjson", import.meta.url),
  "utf8",
)
  .trim()
  .split("\n")
  .map((line) => JSON.parse(line))
  .find((entry) => entry.case === "propose_admin_action/update_market_fees");

describe("quorum UpdateMarketFees", () => {
  it("builds the engine's frozen proposal byte for byte", () => {
    const wire = signAndEncode(
      UNBOUND_CHAIN_ID,
      propose(admin(RAISE_CAP)),
      400n,
      new Uint8Array(32).fill(0x42),
    );
    expect(bytesToHex(wire)).toBe(FROZEN);
  });

  it("decodes the frozen proposal back to its inputs", () => {
    const { action, seq } = decodeTx(hexToBytes(FROZEN));
    expect(seq).toBe(400n);
    expect(action).toEqual(propose(admin(RAISE_CAP_DECODED)));
  });

  it("encodes every field of the change in its own slot and decodes it back", () => {
    expect(vector).toBeDefined();
    const action = propose(admin(EVERY_FIELD, 22n));
    expect(bytesToHex(encodePayloadBytes(action))).toBe(
      vector.expect.payload_hex,
    );
    const tx = encodeSignedTx(
      action,
      12n,
      new Uint8Array(32),
      new Uint8Array(64),
    );
    expect(decodeTx(tx).action).toEqual(action);
  });

  it("reads a tag-35 proposal under its own kind and rejects another tag", () => {
    // The proposal read serves the stored action in the engine's compact
    // form: `[predecessor, change]`, the change's fields by position.
    const tuple = {
      UpdateMarketFees: [
        0,
        [1, ...Array(17).fill(null), 35_000, null, null, null],
      ],
    };
    expect(decodeAdminAction(tuple)).toEqual(admin(RAISE_CAP_DECODED));
    expect(ACTION_TAG_BY_KIND.UpdateMarketFees).toBe(35);
    const raw = [
      1,
      "Pending",
      "Pending",
      1,
      2,
      Array(20).fill(0xa1),
      [],
      [],
      7,
      1000,
      2000,
      35,
      tuple,
      [],
      Array(32).fill(0),
    ];
    expect(decodeProposalDisplayInfo(raw).action).toEqual(
      admin(RAISE_CAP_DECODED),
    );
    raw[11] = 16;
    expect(() => decodeProposalDisplayInfo(raw)).toThrow(
      "does not match UpdateMarketFees tag 35",
    );
  });

  it("refuses a predecessor outside u64", () => {
    expect(() => encodePayloadBytes(propose(admin(RAISE_CAP, -1n)))).toThrow(
      /outside u64::MIN\.\.u64::MAX/,
    );
    expect(() =>
      encodePayloadBytes(propose(admin(RAISE_CAP, 1n << 64n))),
    ).toThrow(/outside u64::MIN\.\.u64::MAX/);
  });
});
