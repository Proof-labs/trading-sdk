// The admin quorum's SetAccountFeeOverride (inner tag 36): one account's taker
// and maker fee, the fee tier a market maker trades at.

import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  decodeTx,
  encodePayloadBytes,
  encodeSignedTx,
  signAndEncode,
} from "./codec.js";
import { bytesToHex, hexToBytes, UNBOUND_CHAIN_ID } from "./crypto.js";
import { ACTION_TAG_BY_KIND, decodeAdminAction } from "./governance-query.js";
import type { AccountFeeOverrideChange, Action, AdminAction } from "./types.js";

/** proof-wire's frozen `vectors/propose_set_account_fee_override.hex`, copied
 *  byte for byte: account `0xDD` × 20 gets a taker fee of 3 and a maker fee
 *  of 0 basis points, its first override (`seq` 1), proposed by `0xA1` × 20
 *  under registry version 1. Key `0x42` × 32 signs it on the unbound chain at
 *  seq 500. */
const FROZEN = readFileSync(
  new URL(
    "../crates/spec/golden-vectors/propose_set_account_fee_override.hex",
    import.meta.url,
  ),
  "utf8",
).trim();

const TIER: AccountFeeOverrideChange = {
  account: new Uint8Array(20).fill(0xdd),
  takerFeeBps: 3,
  makerFeeBps: 0,
  seq: 1n,
};

const admin = (change: AccountFeeOverrideChange): AdminAction => ({
  kind: "SetAccountFeeOverride",
  value: change,
});

const propose = (action: AdminAction): Action => ({
  type: "ProposeAdminAction",
  data: {
    proposer: new Uint8Array(20).fill(0xa1),
    registryVersion: 1n,
    action,
  },
});

// Generated by: cargo run -p proof-trading-sdk-conformance --bin gen-vectors
const vector = readFileSync(
  new URL("../conformance/codec.ndjson", import.meta.url),
  "utf8",
)
  .trim()
  .split("\n")
  .map((line) => JSON.parse(line))
  .find(
    (entry) => entry.case === "propose_admin_action/set_account_fee_override",
  );

describe("quorum SetAccountFeeOverride", () => {
  it("builds the engine's frozen proposal byte for byte", () => {
    const wire = signAndEncode(
      UNBOUND_CHAIN_ID,
      propose(admin(TIER)),
      500n,
      new Uint8Array(32).fill(0x42),
    );
    expect(bytesToHex(wire)).toBe(FROZEN);
  });

  it("decodes the frozen proposal back to its inputs", () => {
    const { action, seq } = decodeTx(hexToBytes(FROZEN));
    expect(seq).toBe(500n);
    expect(action).toEqual(propose(admin(TIER)));
  });

  it("keeps each fee in its own slot, the revert sentinel included", () => {
    expect(vector).toBeDefined();
    const action = propose(
      admin({
        account: new Uint8Array(20).fill(0xdd),
        takerFeeBps: 7,
        makerFeeBps: 0xffff_ffff,
        seq: 9n,
      }),
    );
    expect(bytesToHex(encodePayloadBytes(action))).toBe(
      vector.expect.payload_hex,
    );
    const tx = encodeSignedTx(
      action,
      12n,
      new Uint8Array(32),
      new Uint8Array(64),
    );
    expect(decodeTx(tx).action).toEqual(action);
  });

  it("reads a stored tag-36 action under its own kind", () => {
    const stored = {
      SetAccountFeeOverride: [Array(20).fill(0xdd), 3, 0, 1],
    };
    expect(decodeAdminAction(stored)).toEqual(admin(TIER));
    expect(ACTION_TAG_BY_KIND.SetAccountFeeOverride).toBe(36);
  });

  it("refuses a fee above 10,000 basis points that is not the sentinel", () => {
    expect(() =>
      encodePayloadBytes(propose(admin({ ...TIER, takerFeeBps: 10_001 }))),
    ).toThrow(/takerFeeBps 10001 is outside 0\.\.=10000/);
    expect(() =>
      encodePayloadBytes(propose(admin({ ...TIER, makerFeeBps: -1 }))),
    ).toThrow(/makerFeeBps -1 is outside 0\.\.=10000/);
    expect(() =>
      encodePayloadBytes(propose(admin({ ...TIER, takerFeeBps: 10_000 }))),
    ).not.toThrow();
  });
});
